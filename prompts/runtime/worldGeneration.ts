export type 世界观生成消息 = {
    role: 'system' | 'user' | 'assistant';
    content: string;
};

export const 构建世界观生成消息链 = (params: {
    worldContext: string;
    charData: unknown;
    extraPrompt?: string;
    cotPseudoHistoryPrompt?: string;
    config?: (Partial<游戏设置结构> & Record<string, unknown>) | null;
    openingConfig?: OpeningConfig | null;
}): 世界观生成消息[] => {
    const config = params.config || {};
    const openingConfig = params.openingConfig || (config as any)?.openingConfig || null;
    const normalizedExtraPrompt = (params.extraPrompt || '').trim();
    const normalizedCotPseudoPrompt = (params.cotPseudoHistoryPrompt || '').trim();
    const systemPrompt = 获取世界观生成系统提示词(config, openingConfig);
    const userPrompt = [
        构建世界观生成用户提示词(params.worldContext, params.charData, config, openingConfig),
        normalizedExtraPrompt ? `【最终输出附加要求】\n${normalizedExtraPrompt}` : ''
    ].filter(Boolean).join('\n\n');
    return [
        { role: 'system', content: systemPrompt },
        { role: 'user', content: userPrompt },
        ...(normalizedCotPseudoPrompt ? [{ role: 'assistant' as const, content: normalizedCotPseudoPrompt }] : [])
    ];
};
