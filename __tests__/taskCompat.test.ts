import { describe, expect, it } from 'vitest';
import { 归一化任务类型, 规范化任务奖励描述列表, 规范化任务列表自动结算, 规范化任务自动结算 } from '../utils/taskCompat';

describe('任务分类归一化', () => {
    it('未知任务类型按通用支线处理', () => {
        expect(归一化任务类型({
            类型: '社区委托',
            标题: '临时协助',
            描述: '邻居请你帮忙确认物业门禁登记。'
        })).toBe('支线');
    });

    it('只接受显式合法任务类型', () => {
        expect(归一化任务类型({ 类型: '悬赏', 标题: '同城委托' })).toBe('悬赏');
        expect(归一化任务类型({ 类型: '传闻', 标题: '社区消息' })).toBe('传闻');
        expect(归一化任务类型({ 类型: '委托', 标题: '物业协助' })).toBe('支线');
        expect(归一化任务类型({ 类型: '消息', 标题: '小区传言' })).toBe('支线');
    });

    it('未知类型兜底为支线并保留自动结算', () => {
        const normalized = 规范化任务自动结算({
            类型: '杂事',
            当前状态: '进行中',
            目标列表: [{ 描述: '办完', 当前进度: 1, 总需进度: 1, 完成状态: false }]
        });

        expect(normalized.类型).toBe('支线');
        expect(normalized.当前状态).toBe('已完成');
    });

    it('把对象奖励描述归一为可渲染字符串数组', () => {
        const rewards = 规范化任务奖励描述列表([
            { 类型: '经济', 内容: '元 +500' },
            { 内容: '急救熟练度 +5' },
            '组织信用 +10',
            {},
            null
        ]);

        expect(rewards).toEqual(['经济：元 +500', '急救熟练度 +5', '组织信用 +10']);

        const normalized = 规范化任务自动结算({
            类型: '主线',
            当前状态: '进行中',
            目标列表: [{ 描述: '办完', 当前进度: 1, 总需进度: 1 }],
            奖励描述: [{ 类型: '经济', 内容: '元 +500' }, { 内容: '急救熟练度 +5' }]
        });

        expect(normalized.奖励描述).toEqual(['经济：元 +500', '急救熟练度 +5']);
    });

    it('只去重完全相同的正式任务，不合并相似目标', () => {
        const tasks = 规范化任务列表自动结算([
            {
                标题: '房租协商',
                类型: '主线',
                发布人: '房东',
                发布地点: '出租屋',
                描述: '三天内与房东谈妥缓缴方案。',
                当前状态: '进行中',
                目标列表: [{ 描述: '准备收入证明', 当前进度: 0, 总需进度: 1, 完成状态: false }],
                奖励描述: []
            },
            {
                标题: '整理账单',
                类型: '支线',
                发布人: '室友',
                发布地点: '客厅',
                描述: '室友提醒你把本月水电和房租记录整理清楚。',
                当前状态: '进行中',
                目标列表: [{ 描述: '核对转账记录', 当前进度: 0, 总需进度: 1, 完成状态: false }],
                奖励描述: []
            },
            {
                标题: '整理账单',
                类型: '支线',
                发布人: '室友',
                发布地点: '客厅',
                描述: '室友提醒你把本月水电和房租记录整理清楚。',
                当前状态: '进行中',
                目标列表: [{ 描述: '核对转账记录', 当前进度: 0, 总需进度: 1, 完成状态: false }],
                奖励描述: []
            }
        ]);

        expect(tasks.map((task: any) => task.标题)).toEqual(['房租协商', '整理账单']);
    });
});
